def q(v):
    """مقدار را برای SQL آماده می‌کند."""
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''") + "'"


def build_subsub():
    """زیرزیردسته‌ها را از روی نقشهٔ SUBSUB می‌سازد و شناسه‌های ۱۳۰ تا ۲۸۳ را
    به ترتیب به آن‌ها اختصاص می‌دهد."""
    ids = list(range(130, 284))          # ۱۵۴ شناسه
    out = []
    i = 0
    for sub_id, _, _, _ in SUBS:
        for name in SUBSUB[sub_id]:
            out.append((ids[i], sub_id, name))
            i += 1
    assert i == len(ids), f'تعداد زیرزیردسته‌ها {i} با {len(ids)} تطابق ندارد'
    return out


def slugify_product(idx, name):
    """اسلاگ لاتین برای محصول می‌سازد."""
    return f'kharazi-product-{idx}'


# ─────────────────────────────────────────────────────────────────────
# ۷) تولید SQL
# ─────────────────────────────────────────────────────────────────────
def generate_sql():
    L = []
    A = L.append

    A("-- ============================================================")
    A("-- دادهٔ فروشگاه خرازی پرنسا — دسته‌بندی، زیردسته، محصول و برند")
    A("-- ============================================================")
    A("-- این فایل تمام ردیف‌های موجود را در جای خود به‌روزرسانی می‌کند.")
    A("-- هیچ ردیفی حذف نمی‌شود؛ شناسه‌ها و کلیدهای خارجی حفظ می‌شوند.")
    A("-- ============================================================")
    A("SET NAMES utf8mb4;")
    A("START TRANSACTION;")
    A("")

    # ── دسته‌بندی‌ها
    A("-- ── ۱) دسته‌بندی‌های اصلی (۱۰ ردیف) ──────────────────────")
    for cid, name, slug, meta in CATEGORIES:
        icon = f"uploads/categories/icon/kharazi-cat-{cid}.png"
        banner = f"uploads/categories/banner/kharazi-cat-{cid}.png"
        A(f"UPDATE `categories` SET "
          f"`name`={q(name)}, `slug`={q(slug)}, `top`=1, "
          f"`icon`={q(icon)}, `banner`={q(banner)}, "
          f"`meta_title`={q(name + ' | خرازی پرنسا')}, "
          f"`meta_description`={q(meta)} "
          f"WHERE `id`={cid};")
    A("")

    # ── زیردسته‌ها
    A("-- ── ۲) زیردسته‌ها (۶۰ ردیف) ───────────────────────────────")
    for sid, cid, name, slug in SUBS:
        A(f"UPDATE `sub_categories` SET "
          f"`name`={q(name)}, `category_id`={cid}, `slug`={q(slug)}, "
          f"`meta_title`={q(name + ' | خرازی پرنسا')} "
          f"WHERE `id`={sid};")
    A("")

    # ── زیرزیردسته‌ها
    subs = build_subsub()
    sub_slug = {sid: slug for sid, _, _, slug in SUBS}
    A("-- ── ۳) زیرزیردسته‌ها (۱۵۴ ردیف) ────────────────────────────")
    counter = {}
    for ssid, sid, name in subs:
        counter[sid] = counter.get(sid, 0) + 1
        slug = f"{sub_slug[sid]}-{counter[sid]}"
        A(f"UPDATE `sub_sub_categories` SET "
          f"`sub_category_id`={sid}, `name`={q(name)}, `slug`={q(slug)}, "
          f"`meta_title`={q(name + ' | خرازی پرنسا')} "
          f"WHERE `id`={ssid};")
    A("")

    # ── برندها
    A("-- ── ۴) برندها (۱۵ ردیف) ────────────────────────────────────")
    for bid, name, slug in BRANDS:
        logo = f"uploads/brands/kharazi-brand-{bid}.png"
        A(f"UPDATE `brands` SET `name`={q(name)}, `slug`={q(slug)}, "
          f"`logo`={q(logo)}, `top`=1, "
          f"`meta_title`={q(name + ' | خرازی پرنسا')} WHERE `id`={bid};")
    A("")

    # نقشهٔ زیرزیردسته‌ها: (sub_id) -> [ids]
    sub_to_subsub = {}
    for ssid, sid, name in subs:
        sub_to_subsub.setdefault(sid, []).append(ssid)

    # ── محصولات
    A("-- ── ۵) محصولات (۶۲ ردیف) ──────────────────────────────────")
    for (pid, name, cid, sid, ss_idx, bid, price, purchase, stock,
         unit, desc, tags) in PRODUCTS:
        ssids = sub_to_subsub[sid]
        ssid = ssids[ss_idx] if ss_idx < len(ssids) else ssids[-1]
        slug = slugify_product(pid, name)
        img = f"uploads/products/thumbnail/{slug}.png"
        photos = json.dumps([f"uploads/products/photos/{slug}.png"], ensure_ascii=False)
        A(f"UPDATE `products` SET "
          f"`name`={q(name)}, `slug`={q(slug)}, "
          f"`category_id`={cid}, `subcategory_id`={sid}, `subsubcategory_id`={ssid}, "
          f"`brand_id`={bid}, "
          f"`thumbnail_img`={q(img)}, `featured_img`={q(img)}, "
          f"`flash_deal_img`={q(img)}, `meta_img`={q(img)}, "
          f"`photos`={q(photos)}, "
          f"`tags`={q(tags)}, `description`={q(desc)}, "
          f"`unit_price`={price}, `purchase_price`={purchase}, "
          f"`current_stock`={stock}, `unit`={q(unit)}, "
          f"`meta_title`={q(name + ' | خرازی پرنسا')}, "
          f"`meta_description`={q(desc[:150])}, "
          f"`published`=1 "
          f"WHERE `id`={pid};")
    A("")

    A("COMMIT;")
    A("")
    A("-- ── پایان ───────────────────────────────────────────────────")
    return '\n'.join(L)


def apply_sql(path):
    with open(path, 'rb') as f:
        r = subprocess.run(
            ['mysql', '-uroot', '--default-character-set=utf8mb4', DB],
            stdin=f, capture_output=True)
    return r


def main():
    sql = generate_sql()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       'kharazi-data.sql')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(sql)
    print(f'✅ SQL تولید شد: {out}')
    print(f'   حجم: {len(sql.encode("utf-8"))} بایت')

    if '--apply' in sys.argv:
        r = apply_sql(out)
        if r.returncode == 0:
            print('✅ SQL با موفقیت روی پایگاه داده اعمال شد')
        else:
            print('❌ خطا در اعمال SQL:')
            print(r.stderr.decode('utf-8', 'replace')[:2000])
            sys.exit(1)


if __name__ == '__main__':
    main()
